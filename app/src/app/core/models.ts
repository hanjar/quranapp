export type BookmarkKind = 'verse' | 'page';

export interface Bookmark {
  id: string; // uuid v4
  kind: BookmarkKind;
  editionId: EditionId;
  page: number; // always set (verse bookmarks store the page the ayah was selected on)
  surah: number | null; // required when kind === 'verse'
  ayah: number | null; // required when kind === 'verse'
  /** Semantic dedupe key: `${editionId}|verse|${surah}:${ayah}` or `${editionId}|page|${page}` */
  key: string;
  createdAt: number;
  updatedAt: number;
  deletedAt: number | null; // tombstone
  rev: number | null; // server revision, null = never synced
  /** Folder (collection, e.g. a khatam round) or null = "Tanpa folder". May point to a deleted/unknown folder: treat as null. */
  folderId: string | null;
  /** Optional personal note, trimmed, max BOOKMARK_NOTE_MAX chars. */
  note: string | null;
}

export const BOOKMARK_NOTE_MAX = 500;
export const FOLDER_NAME_MAX = 40;
export const FOLDER_LIMIT = 100;

/**
 * A user-made collection of bookmarks, e.g. "Khatam ke-3" or "Ramadhan 1447 · Khatam 1".
 * Deleting a folder never deletes its bookmarks unless the user explicitly asks;
 * by default they move to "Tanpa folder" (folderId = null).
 */
export interface BookmarkFolder {
  id: string; // uuid v4
  name: string; // trimmed, 1..FOLDER_NAME_MAX chars
  createdAt: number;
  updatedAt: number;
  deletedAt: number | null; // tombstone
  rev: number | null;
}

export interface ReadingPosition {
  editionId: EditionId;
  page: number;
  surah: number | null;
  ayah: number | null;
  updatedAt: number;
  deviceId: string;
  rev: number | null;
}

export interface Preferences {
  paperTheme: PaperTheme;
  uiTheme: UiTheme;
  layoutMode: LayoutMode;
  controlsAlwaysVisible: boolean;
  motion: MotionPref;
  highContrast: boolean;
  onboardingDone: boolean;
  /** Reading-progress goal in pages per day (DAILY_TARGET_MIN..DAILY_TARGET_MAX). Synced. */
  dailyTarget: number;
  /** "Catat progres membaca": false stops recording page views. Synced. */
  trackProgress: boolean;
  updatedAt: number;
  rev: number | null;
}

export const DAILY_TARGET_MIN = 1;
export const DAILY_TARGET_MAX = 40;
export const DEFAULT_DAILY_TARGET = 5;

export function clampDailyTarget(n: number): number {
  if (!Number.isFinite(n)) return DEFAULT_DAILY_TARGET;
  return Math.min(DAILY_TARGET_MAX, Math.max(DAILY_TARGET_MIN, Math.round(n)));
}

