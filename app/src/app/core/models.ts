/**
 * Frozen domain contracts shared by every feature. Changing a shape here is a
 * cross-cutting decision — update docs/ARCHITECTURE.md alongside it.
 */

export type EditionId = 'hafs-kfqc';
export const DEFAULT_EDITION: EditionId = 'hafs-kfqc';
export const PAGE_COUNT = 604;

export type PaperTheme = 'photo' | 'ivory' | 'antique' | 'cream';
export type UiTheme = 'klasik' | 'segar' | 'ceria' | 'samudra';
export type LayoutMode = 'auto' | 'single' | 'spread';
export type MotionPref = 'system' | 'reduce';

export interface AyahRef {
  surah: number; // 1–114
  ayah: number; // 1–ayahCount
}

// ---------------------------------------------------------------------------
// Content metadata (read-only, generated by scripts/build-content.mjs into
// app/public/content/<editionId>/). Never hand-edited.
// ---------------------------------------------------------------------------

export interface Edition {
  editionId: EditionId;
  riwayah: 'hafs';
  pageCount: number; // 604
  /** Upstream commit SHA (short) the artwork + polygons were taken from. */
  contentVersion: string;
  source: { repo: string; commit: string; path: string };
  license: { artwork: string; metadata: string };
  attribution: string;
}

export interface SurahMeta {
  number: number;
  nameArabic: string;
  /** Indonesian transliteration, e.g. "Al-Baqarah". */
  nameLatin: string;
  /** Upstream English name, e.g. "Al-Baqara". Kept for search. */
  nameEnglish: string;
  ayahCount: number;
  startPage: number;
  endPage: number;
  /** Juz containing ayah 1 of this surah. */
  juz: number;
}

export interface PageMeta {
  page: number;
  first: AyahRef;
  last: AyahRef;
  /** Surah numbers with at least one ayah on this page, ascending. */
  surahs: number[];
  /** Juz containing `first`. */
  juz: number;
  /** Juz numbers that START on this page (usually empty). */
  juzStarts: number[];
}

export interface JuzMeta {
  number: number; // 1–30
  start: AyahRef;
  page: number;
}

export interface ContentManifest {
  editionId: EditionId;
  contentVersion: string;
  /** keys are paths relative to the edition folder, e.g. "svg/003.svg" */
  files: Record<string, { sha256: string; bytes: number }>;
  totalBytes: number;
}

export interface ContentIndex {
  edition: Edition;
  surahs: SurahMeta[]; // index 0 = surah 1
  pages: PageMeta[]; // index 0 = page 1
  juz: JuzMeta[]; // index 0 = juz 1
}

export type PageLoadErrorKind = 'offline' | 'network' | 'integrity' | 'not-found';

export class PageLoadError extends Error {
  constructor(
    readonly page: number,
    readonly kind: PageLoadErrorKind,
    message?: string,
  ) {
    super(message ?? `Halaman ${page} gagal dimuat (${kind})`);
    this.name = 'PageLoadError';
  }
}

// ---------------------------------------------------------------------------
// User data (IndexedDB, optionally synced). Timestamps are epoch ms.
// ---------------------------------------------------------------------------

export type BookmarkKind = 'verse' | 'page';

export interface Bookmark {
  id: string; // uuid v4
  kind: BookmarkKind;
  editionId: EditionId;
  page: number; // always set (verse bookmarks store the page the ayah was selected on)
  surah: number | null; // required when kind === 'verse'
  ayah: number | null; // required when kind === 'verse'
  /** Semantic dedupe key: `${editionId}|verse|${surah}:${ayah}` or `${editionId}|page|${page}` */
  key: string;
  createdAt: number;
  updatedAt: number;
  deletedAt: number | null; // tombstone
  rev: number | null; // server revision, null = never synced
}

export interface ReadingPosition {
  editionId: EditionId;
  page: number;
  surah: number | null;
  ayah: number | null;
  updatedAt: number;
  deviceId: string;
  rev: number | null;
}

export interface Preferences {
  paperTheme: PaperTheme;
  uiTheme: UiTheme;
  layoutMode: LayoutMode;
  controlsAlwaysVisible: boolean;
  motion: MotionPref;
  highContrast: boolean;
  onboardingDone: boolean;
  updatedAt: number;
  rev: number | null;
}

export const DEFAULT_PREFERENCES: Preferences = {
  paperTheme: 'cream',
  uiTheme: 'segar',
  layoutMode: 'auto',
  controlsAlwaysVisible: false,
  motion: 'system',
  highContrast: false,
  onboardingDone: false,
  updatedAt: 0,
  rev: null,
};

export type SyncEntity = 'bookmark' | 'position' | 'prefs';

export interface OutboxOperation {
  opId: string; // uuid v4, idempotency key
  accountId: string; // ops are isolated per account
  entity: SyncEntity;
  entityId: string; // bookmark.id | editionId | 'prefs'
  action: 'upsert' | 'delete';
  payload: unknown;
  baseRev: number | null;
  createdAt: number;
  retryCount: number;
  nextAttemptAt: number;
}

export type SyncStatus =
  | 'off' // guest / sync disabled
  | 'idle' // enabled, nothing pending
  | 'pending' // local changes waiting
  | 'syncing'
  | 'synced'
  | 'offline'
  | 'error'
  | 'conflict' // reading position needs a user choice
  | 'unauthorized'; // session expired → re-login

export interface SyncState {
  key: 'state';
  enabled: boolean;
  accountId: string | null;
  cursor: number;
  lastSuccessAt: number | null;
  status: SyncStatus;
  lastErrorCode: string | null;
}

export interface Account {
  id: string;
  email: string | null;
  name: string | null;
}

/** Shape of the versioned export/import file (US-12). */
export interface ExportFile {
  format: 'mushaf-digital-export';
  version: 1;
  exportedAt: number;
  editionId: EditionId;
  bookmarks: Bookmark[];
  position: ReadingPosition | null;
  preferences: Preferences;
}

// ---------------------------------------------------------------------------
// Helpers shared by stores and sync.
// ---------------------------------------------------------------------------

export function bookmarkKey(
  editionId: EditionId,
  kind: BookmarkKind,
  target: { page?: number | null; surah?: number | null; ayah?: number | null },
): string {
  return kind === 'verse'
    ? `${editionId}|verse|${target.surah}:${target.ayah}`
    : `${editionId}|page|${target.page}`;
}

export function isValidPage(p: unknown): p is number {
  return Number.isInteger(p) && (p as number) >= 1 && (p as number) <= PAGE_COUNT;
}

export function uuid(): string {
  return crypto.randomUUID();
}
