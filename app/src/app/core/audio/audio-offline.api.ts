import { Signal } from '@angular/core';
import { AyahRef } from '../models';

/** Offline audio quality, chosen by the user (owner decision, D20). */
export type AudioVariant = 'opus24' | 'opus32' | 'mp364';

/** Where offline audio lives: Cloudflare R2 bucket `mushaf-audio`, CORS for the app origin. */
export const AUDIO_BASE = 'https://audio.hanjar.net/alafasy';
export const AUDIO_MANIFEST_URL = `${AUDIO_BASE}/audio-manifest.json`;
/** `${AUDIO_BASE}/${variant}/${SSS}${AAA}.${ext}`, e.g. .../opus24/055013.webm */
export function audioFileUrl(variant: AudioVariant, ext: string, ref: AyahRef): string {
  const p = (n: number) => String(n).padStart(3, '0');
  return `${AUDIO_BASE}/${variant}/${p(ref.surah)}${p(ref.ayah)}.${ext}`;
}

/** Shape of audio-manifest.json (generated by scripts/build-audio.mjs). */
export interface AudioManifest {
  format: 'mushaf-audio';
  version: 1;
  qari: { id: string; name: string; source: string; license: string; builtAt: string };
  variants: Record<
    AudioVariant,
    { label: string; ext: string; mime: string; kbps: number; totalBytes: number; bytes: number[] }
  >;
  ayahCount: number;
}

export type AudioScope =
  { kind: 'surah'; id: number } | { kind: 'juz'; id: number } | { kind: 'all' };

export interface AudioDownloadStatus {
  state: 'idle' | 'downloading' | 'paused' | 'done' | 'error' | 'quota';
  /** What is being (or was last) downloaded. */
  scope: AudioScope | null;
  done: number; // ayah files verified in the cache for `scope`
  total: number; // ayah files in `scope`
  bytesDone: number;
  bytesTotal: number;
  failed: number; // ayah files that failed in the last run
}

/**
 * Offline recitation packages. Files are fetched with CORS from R2 and stored in
 * Cache Storage `mushaf-audio-<qari>-<variant>`; playback asks `localUrl()` first.
 * Impl: core/audio/audio-offline.service.ts (bound in app.config.ts).
 */
export abstract class AudioOfflineApi {
  /** Manifest (sizes); null until loaded or when offline on first use. */
  abstract readonly manifest: Signal<AudioManifest | null>;
  /** Variants this browser can play (Opus needs `audio/webm; codecs=opus`). Order: opus24, opus32, mp364. */
  abstract readonly supported: Signal<AudioVariant[]>;
  /** Chosen quality (persisted on this device). Default: opus24 if supported, else mp364. */
  abstract readonly variant: Signal<AudioVariant>;
  abstract readonly status: Signal<AudioDownloadStatus>;
  /** Downloaded ayah count per surah for the current variant (index 0 = surah 1). */
  abstract readonly perSurah: Signal<number[]>;
  /** Total bytes of audio stored for the current variant. */
  abstract readonly usedBytes: Signal<number>;

  abstract load(): Promise<void>;
  /** Bytes of `scope` for a variant (default: current), from the manifest. */
  abstract sizeOf(scope: AudioScope, variant?: AudioVariant): number;
  /** Ayahs in `scope` that are already stored / total. */
  abstract progressOf(scope: AudioScope): { done: number; total: number };

  /** Switches quality; deletes audio stored in the other variants. */
  abstract setVariant(v: AudioVariant): Promise<void>;
  abstract download(scope: AudioScope): Promise<void>;
  abstract pause(): void;
  abstract resume(): Promise<void>;
  /** Removes stored audio for `scope` (all = everything, every variant). */
  abstract remove(scope: AudioScope): Promise<void>;

  /** Object URL for a stored ayah in the current variant, or null (→ stream instead). */
  abstract localUrl(ref: AyahRef): Promise<string | null>;
}
